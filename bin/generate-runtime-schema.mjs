// Generate the explicit, reviewed initial domain DDL from the shipped schema only.
// Never opens a user database. This is a development tool, not a migration command.
import { DatabaseSync } from 'node:sqlite';
import fs from 'node:fs';
const db = new DatabaseSync(':memory:');
db.exec(fs.readFileSync('server/schema.sql', 'utf8'));
for (const file of fs
  .readdirSync('server/migrations')
  .filter((f) => /^\d.*\.sql$/.test(f))
  .sort())
  db.exec(fs.readFileSync('server/migrations/' + file, 'utf8'));
const excluded = new Set([
  'migrations',
  'workers',
  'sqlite_sequence',
  'chunk_search',
  'chunk_search_data',
  'chunk_search_idx',
  'chunk_search_content',
  'chunk_search_docsize',
  'chunk_search_config',
]);
const derived = {
  versions: 'workflows',
  steps: 'runs',
  events: 'runs',
  actions: 'runs',
  tool_approvals: 'steps',
  evaluation_cases: 'evaluations',
  prompt_versions: 'prompt_library',
};
const tables = db
  .prepare("SELECT name FROM sqlite_master WHERE type='table' ORDER BY rowid")
  .all()
  .filter((r) => !excluded.has(r.name));
let sql =
  '-- Initial legacy-domain storage. Text JSON and epoch fields intentionally preserve import fidelity.\n';
for (const { name } of tables) {
  const columns = db.prepare(`PRAGMA table_info("${name}")`).all();
  const pk = columns.filter((c) => c.pk).sort((a, b) => a.pk - b.pk);
  const fields = columns.map((c) => {
    const type = c.type === 'INTEGER' ? 'bigint' : c.type === 'REAL' ? 'double precision' : 'text';
    return `  ${c.name} ${name === 'events' && c.name === 'id' ? 'bigint GENERATED BY DEFAULT AS IDENTITY' : type}${c.notnull || c.pk ? ' NOT NULL' : ''}${c.dflt_value !== null ? ' DEFAULT ' + c.dflt_value : ''}`;
  });
  if (derived[name] && !columns.some((c) => c.name === 'workspace_id'))
    fields.push('  workspace_id text NOT NULL');
  fields.push(`  PRIMARY KEY (${pk.map((c) => c.name).join(',')})`);
  for (const idx of db
    .prepare(`PRAGMA index_list("${name}")`)
    .all()
    .filter((i) => i.unique && i.origin !== 'pk')) {
    const cols = db
      .prepare(`PRAGMA index_info("${idx.name}")`)
      .all()
      .map((c) => c.name);
    fields.push(`  UNIQUE (${cols.join(',')})`);
  }
  sql += `CREATE TABLE relay.${name} (\n${fields.join(',\n')}\n);\n`;
}
// Add references after all tables exist; derived tenant scope is enforced separately below.
for (const { name } of tables) {
  for (const fk of db.prepare(`PRAGMA foreign_key_list("${name}")`).all())
    sql += `ALTER TABLE relay.${name} ADD FOREIGN KEY (${fk.from}) REFERENCES relay.${fk.table}(${fk.to}) ON DELETE ${fk.on_delete};\n`;
  const scoped =
    name === 'workspaces' ||
    derived[name] ||
    db
      .prepare(`PRAGMA table_info("${name}")`)
      .all()
      .some((c) => c.name === 'workspace_id');
  if (scoped) {
    const col = name === 'workspaces' ? 'id' : 'workspace_id';
    sql += `ALTER TABLE relay.${name} ENABLE ROW LEVEL SECURITY;\nALTER TABLE relay.${name} FORCE ROW LEVEL SECURITY;\nCREATE POLICY ${name}_workspace ON relay.${name} USING (${col}=nullif(current_setting('relay.workspace_id',true),'')) WITH CHECK (${col}=nullif(current_setting('relay.workspace_id',true),''));\n`;
    if (name !== 'workspaces')
      sql += `CREATE INDEX ${name}_tenant ON relay.${name}(workspace_id);\n`;
  }
}
// A scoped child may never reference an ID belonging to another workspace.
const scopedNames = new Set(
  tables
    .filter(
      ({ name }) =>
        name === 'workspaces' ||
        derived[name] ||
        db
          .prepare(`PRAGMA table_info("${name}")`)
          .all()
          .some((c) => c.name === 'workspace_id'),
    )
    .map((t) => t.name),
);
for (const name of scopedNames) {
  if (
    name !== 'workspaces' &&
    db
      .prepare(`PRAGMA table_info("${name}")`)
      .all()
      .some((c) => c.name === 'id')
  )
    sql += `ALTER TABLE relay.${name} ADD UNIQUE(workspace_id,id);\n`;
}
for (const { name } of tables)
  if (scopedNames.has(name)) {
    for (const fk of db.prepare(`PRAGMA foreign_key_list("${name}")`).all())
      if (scopedNames.has(fk.table) && fk.table !== 'workspaces' && fk.to === 'id')
        sql += `ALTER TABLE relay.${name} ADD FOREIGN KEY(workspace_id,${fk.from}) REFERENCES relay.${fk.table}(workspace_id,id) ON DELETE ${fk.on_delete};\n`;
  }
sql +=
  "ALTER TABLE relay.members ADD CHECK(role IN ('owner','administrator','editor','viewer'));\n";
fs.mkdirSync('server/runtime', { recursive: true });
fs.writeFileSync('server/migrations/postgres/0100-domain.sql', sql);
fs.writeFileSync(
  'server/runtime/import-manifest.json',
  JSON.stringify(
    tables.map(({ name }) => ({
      name,
      columns: db
        .prepare(`PRAGMA table_info("${name}")`)
        .all()
        .map((c) => c.name),
      parent: derived[name] || null,
      fks: db.prepare(`PRAGMA foreign_key_list("${name}")`).all(),
    })),
    null,
    2,
  ) + '\n',
);
db.close();
